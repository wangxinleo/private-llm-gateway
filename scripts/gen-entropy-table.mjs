// 生成 src/scanner/entropy-table.ts：自算英文 bigram 代价表。
// 语料：Project Gutenberg #1342（公有领域）；缓存于 node_modules/.cache，
// 缺失时按 URL 下载；语料 sha256 写入生成物头部以便复核。
// 用法：node scripts/gen-entropy-table.mjs [--corpus <path>]

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ALPHA, SYM_COUNT, buildTable } from "./entropy-lib.mjs";

const CORPUS_URL = "https://www.gutenberg.org/files/1342/1342-0.txt";
const CORPUS_TITLE = "Project Gutenberg #1342 — Pride and Prejudice (Jane Austen, public domain)";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cachePath = resolve(root, "node_modules/.cache/entropy-corpus.txt");

function loadCorpus() {
  const argIdx = process.argv.indexOf("--corpus");
  if (argIdx !== -1) return readFileSync(resolve(process.argv[argIdx + 1]));
  if (existsSync(cachePath)) return readFileSync(cachePath);
  mkdirSync(dirname(cachePath), { recursive: true });
  const res = spawnSync("curl", ["-sSfL", CORPUS_URL]);
  if (res.status !== 0) {
    throw new Error(`corpus download failed: ${res.stderr?.toString() ?? "unknown"}; pass --corpus <path>`);
  }
  writeFileSync(cachePath, res.stdout);
  return res.stdout;
}

const corpus = loadCorpus();
const sha256 = createHash("sha256").update(corpus).digest("hex");
const table = buildTable(corpus.toString("utf8"));

// 未使用单元（如 prev='$' 行、ch='^' 列）保持 0；评分只读取已用单元
const fmt = (n) => (Number.isFinite(n) && n > 0 ? n.toFixed(4) : "0.0000");
const rows = [];
for (let prev = 0; prev < SYM_COUNT; prev++) {
  const cells = [];
  for (let ch = 0; ch < SYM_COUNT; ch++) cells.push(fmt(table[prev * SYM_COUNT + ch]));
  rows.push(`  /* ${String(prev).padStart(2, "0")} */ ${cells.join(",")},`);
}

const out = `// AUTO-GENERATED by scripts/gen-entropy-table.mjs — DO NOT EDIT BY HAND.
// 语料: ${CORPUS_TITLE}
// 来源: ${CORPUS_URL}
// sha256: ${sha256}
// 平滑: add-α α=${ALPHA}, V=${SYM_COUNT}; 符号: a-z=0..25, '#'=26(数字类), '^'=27, '$'=28
// 代价: -log2(P(ch|prev)); 扁平数组, 下标 = prev * ${SYM_COUNT} + ch（每行一条注释仅为可读性）

export const ENTROPY_COST_TABLE: readonly number[] = [
${rows.join("\n")}
];

export const ENTROPY_SYMBOL_COUNT = ${SYM_COUNT};
`;

writeFileSync(resolve(root, "src/scanner/entropy-table.ts"), out);
console.log(`generated src/scanner/entropy-table.ts | corpus sha256=${sha256.slice(0, 16)}… | rows=${SYM_COUNT}`);
